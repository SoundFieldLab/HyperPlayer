pub fn routes() -> &'static [RouteSpec] {
    &ROUTES
}
pub fn capability(name: &str) -> Option<&'static RouteSpec> {
    ROUTES.iter().find(|x| x.name == name)
}
pub fn base_url(channel: Channel) -> Option<&'static str> {
    match channel {
        Channel::Eapi => Some(PC),
        Channel::Xeapi => Some(A),
        Channel::Public => Some(W),
        Channel::Clientlog => Some(L),
        Channel::Local | Channel::Composite => None,
    }
}

