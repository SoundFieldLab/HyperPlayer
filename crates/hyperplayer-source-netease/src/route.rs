#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Channel {
    Eapi,
    Xeapi,
    Public,
    Clientlog,
    Local,
    Composite,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Capability {
    Read,
    Write,
    Aggregate,
    Transform,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RouteSpec {
    pub name: &'static str,
    pub domain: &'static str,
    pub path: &'static str,
    pub channel: Channel,
    pub capability: Capability,
    pub login_required: bool,
    pub anti_cheat: bool,
}
