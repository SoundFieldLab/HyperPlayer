// HyperPlayer adaptations: vendored 网易云协议包浏览器化 —— 构建期静态枚举 + esbuild 打包。
// 复刻 vendor main.js 的模块发现/包装逻辑（cookie 处理 + request 注入），
// 但不引入 express 入口（server.js）与 fs 运行时自动发现（静态枚举）。
// 排除红线模块（unblock/跨平台匹配）与上传类模块（需 express-fileupload/fs 流）。

import { build } from 'esbuild'
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const vendorRoot = resolve(root, 'vendor/netease-cloudmusic-api')
const moduleDir = resolve(vendorRoot, 'module')
const dataDir = resolve(vendorRoot, 'data')
const outDir = resolve(root, 'app/services/netease/generated')
const shimsDir = resolve(root, 'app/services/netease/shims')

// 红线 / 浏览器不可用模块：unblock 路径（song_url_match / song_url_v1）、
// 云盘/语音上传（cloud / voice_upload，依赖 express-fileupload 形态的 fs 流）
const EXCLUDED = new Set(['song_url_match.js', 'song_url_v1.js', 'cloud.js', 'voice_upload.js'])

const modules = readdirSync(moduleDir)
  .filter((file) => file.endsWith('.js') && !EXCLUDED.has(file))
  .sort()

mkdirSync(outDir, { recursive: true })

// ---- 内联 china_ip_ranges.txt（fs shim 无真实文件系统） ----
const chinaIpRanges = readFileSync(resolve(dataDir, 'china_ip_ranges.txt'), 'utf-8')
const chinaIpRangesPath = resolve(outDir, 'china-ip-ranges.generated.ts')
writeFileSync(
  chinaIpRangesPath,
  `// GENERATED by scripts/build-netease-vendor.mjs — do not edit
export const CHINA_IP_RANGES_CONTENT = ${JSON.stringify(chinaIpRanges)}
`,
  'utf-8',
)

// ---- 生成静态 registry（复刻 main.js 的 obj[fn] 包装，静态 import 便于 esbuild 打包） ----
const registryLines = [
  '// GENERATED by scripts/build-netease-vendor.mjs — do not edit',
  "import '../shims/node-globals.mjs'",
  `import { cookieToJson } from '${resolve(vendorRoot, 'util/index.js').replace(/\\/g, '/')}'`,
  `import createRequest from '${resolve(vendorRoot, 'util/request.js').replace(/\\/g, '/')}'`,
  '',
]
for (const file of modules) {
  const name = file.slice(0, -3)
  const ident = `module_${name.replace(/[^a-zA-Z0-9_$]/g, '_')}`
  registryLines.push(
    `import ${ident} from '${resolve(moduleDir, file).replace(/\\/g, '/')}'`,
  )
}
registryLines.push('')
registryLines.push('function wrap(module) {')
registryLines.push('  return function (data = {}) {')
registryLines.push(
  "    const cookie = typeof data.cookie === 'string' ? cookieToJson(data.cookie) : data.cookie || {}",
)
registryLines.push('    return module({ ...data, cookie }, (...args) => createRequest(...args))')
registryLines.push('  }')
registryLines.push('}')
registryLines.push('')
registryLines.push('const api = {')
for (const file of modules) {
  const name = file.slice(0, -3)
  const ident = `module_${name.replace(/[^a-zA-Z0-9_$]/g, '_')}`
  registryLines.push(`  ${JSON.stringify(name)}: wrap(${ident}),`)
}
registryLines.push('}')
registryLines.push('')
registryLines.push('export default api')

const registryPath = resolve(outDir, 'netease-registry.generated.mjs')
writeFileSync(registryPath, registryLines.join('\n'), 'utf-8')

// ---- esbuild 打包：Node 内置模块 → 浏览器 shim ----
const alias = {}
for (const name of ['fs', 'os', 'path', 'crypto', 'zlib', 'http', 'https', 'url', 'axios', 'qrcode']) {
  alias[name] = resolve(shimsDir, name === 'http' || name === 'https' ? 'http.ts' : `${name}.ts`)
}
// 协议包顶层 require 的 Node 专用依赖 → 空 stub（浏览器不启用代理/环境变量）
for (const name of ['tunnel', 'pac-proxy-agent', 'dotenv', 'music-metadata', 'xml2js']) {
  alias[name] = resolve(shimsDir, 'empty.ts')
}

const outFile = resolve(outDir, 'netease-api.generated.js')
const result = await build({
  entryPoints: [registryPath],
  bundle: true,
  platform: 'browser',
  format: 'esm',
  target: 'es2022',
  outfile: outFile,
  logLevel: 'warning',
  alias,
  // vendored 代码用 __dirname 拼 china_ip_ranges 路径；浏览器端固定为虚拟根
  define: { __dirname: '"/"' },
})

if (result.errors.length > 0) {
  for (const error of result.errors) {
    console.error(
      `[esbuild] ${error.location?.file ?? ''}:${error.location?.line ?? 0}:${error.location?.column ?? 0} ${error.text}`,
    )
  }
  process.exit(1)
}

// ---- 生成类型声明（复用 vendored interface.d.ts 的 405 个签名） ----
const dtsPath = resolve(outDir, 'netease-api.generated.d.ts')
const dts = [
  '// GENERATED by scripts/build-netease-vendor.mjs — do not edit',
  "import type * as NeteaseApi from '../../../../vendor/netease-cloudmusic-api/interface'",
  '',
  'declare const api: typeof NeteaseApi',
  'export default api',
  '',
].join('\n')
writeFileSync(dtsPath, dts, 'utf-8')

const bytes = readFileSync(outFile, 'utf-8').length
console.log(`netease vendor bundle: ${modules.length} modules → ${outFile} (${bytes} bytes)`)
