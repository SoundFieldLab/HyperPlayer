import { createHash } from 'node:crypto'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import decodeHeic from 'heic-decode'
import sharp from 'sharp'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = path.resolve(projectRoot, '..', 'weather_assets', 'Mica')
const outputRoot = path.join(projectRoot, 'src', 'assets', 'weather', 'apple-scene')
const textureRoot = path.join(outputRoot, 'textures')
const camlRoot = path.join(outputRoot, 'caml')
const generatedModule = path.join(projectRoot, 'src', 'components', 'weatherScene', 'appleWeatherAssets.generated.ts')

const scenes = {
  'clear-day': 'sunny@3x-812h.caml',
  'clear-night': 'clear@3x-812h.caml',
  'partly-cloudy-day': 'partlyCloudy_day@3x-812h.caml',
  'partly-cloudy-night': 'partlyCloudy_night@3x-812h.caml',
  'cloudy-day': 'cloudy_day@3x-812h.caml',
  'cloudy-night': 'cloudy_night@3x-812h.caml',
  'fog-day': 'fog_day@3x-812h.caml',
  'fog-night': 'fog_night@3x-812h.caml',
  'drizzle-day': 'drizzle_day@3x-812h.caml',
  'drizzle-night': 'drizzle_night@3x-812h.caml',
  'rain-day': 'rain_day@3x-812h.caml',
  'rain-night': 'rain_night@3x-812h.caml',
  'heavy-rain-day': 'heavyRain_day@3x-812h.caml',
  'heavy-rain-night': 'heavyRain_night@3x-812h.caml',
  'thunder-day': 'thunderstorm_day@3x-812h.caml',
  'thunder-night': 'thunderstorm_night@3x-812h.caml',
  'snow-day': 'snow_day@3x-812h.caml',
  'snow-night': 'snow_night@3x-812h.caml',
}

const sha256 = value => createHash('sha256').update(value).digest('hex')
const identifier = value => `texture_${value.replace(/[^a-zA-Z0-9]/g, '_')}`

await rm(outputRoot, { recursive: true, force: true })
await mkdir(textureRoot, { recursive: true })
await mkdir(camlRoot, { recursive: true })

const sceneEntries = []
const textureNames = new Set()

for (const [id, filename] of Object.entries(scenes)) {
  const sourcePath = path.join(sourceRoot, filename)
  const xml = await readFile(sourcePath, 'utf8')
  const assets = [...xml.matchAll(/<contents\s+src="assets\/([^"]+)"/g)].map(match => match[1])
  const uniqueAssets = [...new Set(assets)]
  uniqueAssets.forEach(asset => textureNames.add(asset))
  await copyFile(sourcePath, path.join(camlRoot, filename))
  sceneEntries.push({ id, caml: filename, hash: sha256(xml), assets: uniqueAssets })
}

const textureEntries = []
const unsupportedTextures = []
for (const filename of [...textureNames].sort()) {
  const sourcePath = path.join(sourceRoot, filename)
  const outputName = filename.replace(/\.heic$/i, '.webp')
  const outputPath = path.join(textureRoot, outputName)
  try {
    const source = await readFile(sourcePath)
    const decoded = await decodeHeic({ buffer: source })
    await sharp(Buffer.from(decoded.data), { raw: { width: decoded.width, height: decoded.height, channels: 4 } })
      .webp({ lossless: true, effort: 6 })
      .toFile(outputPath)
    textureEntries.push({ source: filename, output: outputName, width: decoded.width, height: decoded.height, frames: 1 })
  } catch (error) {
    unsupportedTextures.push({ source: filename, reason: error instanceof Error ? error.message.split('\n')[0] : String(error) })
  }
}

const imports = textureEntries.map(texture => `import ${identifier(texture.source)} from '../../assets/weather/apple-scene/textures/${texture.output}'`).join('\n')
const textureObject = textureEntries.map(texture => `  ${JSON.stringify(texture.source)}: { url: ${identifier(texture.source)}, width: ${texture.width}, height: ${texture.height}, frames: ${texture.frames} },`).join('\n')
const sceneObject = Object.fromEntries(sceneEntries.map(scene => [scene.id, scene]))
const moduleSource = `// Generated by scripts/build-apple-weather-scenes.mjs. Do not edit by hand.\n${imports}\n\nexport interface AppleWeatherTextureAsset {\n  url: string\n  width: number\n  height: number\n  frames: number\n}\n\nexport const APPLE_WEATHER_TEXTURES: Record<string, AppleWeatherTextureAsset> = {\n${textureObject}\n}\n\nexport const APPLE_WEATHER_SCENES = ${JSON.stringify(sceneObject, null, 2)} as const\n`

await writeFile(generatedModule, moduleSource)
await writeFile(path.join(outputRoot, 'manifest.json'), JSON.stringify({ version: 1, authoredSize: [640, 1136], scenes: sceneEntries, textures: textureEntries, unsupportedTextures }, null, 2))
console.log(`Built ${sceneEntries.length} Apple weather scenes with ${textureEntries.length} original textures (${unsupportedTextures.length} unsupported).`)
